#!/usr/bin/env bash

# 文件职责：
# 在 Linux 上以前台方式启动 hello_service。
# 调用流程：
# 1. 先加载同目录 deploy.env。
# 2. 再把服务监听、MySQL、Redis、OTel 环境变量注入进程。
# 3. 最后 exec hello_service，交给 systemd 或终端接管。

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
DEPLOY_ENV="${DEPLOY_ENV:-${SCRIPT_DIR}/deploy.env}"
BUILD_DIR="${BUILD_DIR:-${PROJECT_ROOT}/build}"
SERVICE_BIN="${SERVICE_BIN:-${BUILD_DIR}/hello_service}"

if [[ -f "${DEPLOY_ENV}" ]]; then
  # shellcheck disable=SC1090
  source "${DEPLOY_ENV}"
fi

export HELLO_SERVICE_NAME="${HELLO_SERVICE_NAME:-ue-game-backend}"
export HELLO_SERVICE_ENV="${HELLO_SERVICE_ENV:-production}"
export HELLO_SERVICE_HOST="${HELLO_SERVICE_HOST:-0.0.0.0}"
export HELLO_SERVICE_PORT="${HELLO_SERVICE_PORT:-8080}"
export HELLO_SERVICE_STORAGE_MODE="${HELLO_SERVICE_STORAGE_MODE:-mysql_redis}"
export HELLO_SERVICE_MYSQL_HOST="${HELLO_SERVICE_MYSQL_HOST:-127.0.0.1}"
export HELLO_SERVICE_MYSQL_PORT="${HELLO_SERVICE_MYSQL_PORT:-3306}"
export HELLO_SERVICE_MYSQL_USER="${HELLO_SERVICE_MYSQL_USER:-game_backend}"
export HELLO_SERVICE_MYSQL_PASSWORD="${HELLO_SERVICE_MYSQL_PASSWORD:-change_me}"
export HELLO_SERVICE_MYSQL_DATABASE="${HELLO_SERVICE_MYSQL_DATABASE:-game_backend}"
export HELLO_SERVICE_MYSQL_AUTO_MIGRATE="${HELLO_SERVICE_MYSQL_AUTO_MIGRATE:-1}"
export HELLO_SERVICE_MYSQL_SCHEMA_FILE="${HELLO_SERVICE_MYSQL_SCHEMA_FILE:-db/mysql/001_game_backend.sql}"
export HELLO_SERVICE_REDIS_HOST="${HELLO_SERVICE_REDIS_HOST:-127.0.0.1}"
export HELLO_SERVICE_REDIS_PORT="${HELLO_SERVICE_REDIS_PORT:-6379}"
export HELLO_SERVICE_REDIS_PASSWORD="${HELLO_SERVICE_REDIS_PASSWORD:-}"
export HELLO_SERVICE_REDIS_DB="${HELLO_SERVICE_REDIS_DB:-0}"
export HELLO_SERVICE_REDIS_POOL_SIZE="${HELLO_SERVICE_REDIS_POOL_SIZE:-16}"
export HELLO_SERVICE_SERIALIZE_MUTATING_REQUESTS="${HELLO_SERVICE_SERIALIZE_MUTATING_REQUESTS:-true}"
export HELLO_SERVICE_MAX_PENDING_TASKS_PER_KEY="${HELLO_SERVICE_MAX_PENDING_TASKS_PER_KEY:-256}"
export HELLO_SERVICE_GM_TOKEN="${HELLO_SERVICE_GM_TOKEN:-change_me_gm_token}"
export HELLO_SERVICE_REQUEST_LOG_SAMPLE_RATE="${HELLO_SERVICE_REQUEST_LOG_SAMPLE_RATE:-10}"
export HELLO_SERVICE_AUTO_BOOTSTRAP_DEV_ADMIN="${HELLO_SERVICE_AUTO_BOOTSTRAP_DEV_ADMIN:-0}"
export HELLO_SERVICE_LIVEKIT_URL="${HELLO_SERVICE_LIVEKIT_URL:-}"
export HELLO_SERVICE_LIVEKIT_API_KEY="${HELLO_SERVICE_LIVEKIT_API_KEY:-}"
export HELLO_SERVICE_LIVEKIT_API_SECRET="${HELLO_SERVICE_LIVEKIT_API_SECRET:-}"
export HELLO_SERVICE_VOICE_TOKEN_TTL_SECONDS="${HELLO_SERVICE_VOICE_TOKEN_TTL_SECONDS:-900}"
export HELLO_SERVICE_VOICE_ROOM_PREFIX="${HELLO_SERVICE_VOICE_ROOM_PREFIX:-blaster}"
export OTEL_EXPORTER_OTLP_ENDPOINT="${OTEL_EXPORTER_OTLP_ENDPOINT:-http://127.0.0.1:4318}"
export OTEL_EXPORTER_OTLP_TRACES_ENDPOINT="${OTEL_EXPORTER_OTLP_TRACES_ENDPOINT:-http://127.0.0.1:4318/v1/traces}"
export OTEL_EXPORTER_OTLP_METRICS_ENDPOINT="${OTEL_EXPORTER_OTLP_METRICS_ENDPOINT:-http://127.0.0.1:4318/v1/metrics}"

exec "${SERVICE_BIN}"
