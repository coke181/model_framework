#!/usr/bin/env bash

# 文件职责：
# 在 Linux 上启动后台任务 worker。
# 调用流程：
# 1. 加载 deploy.env。
# 2. 注入 MySQL、Redis、OTel 环境变量。
# 3. 前台 exec hello_task_worker，交给 systemd 守护。

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
DEPLOY_ENV="${DEPLOY_ENV:-${SCRIPT_DIR}/deploy.env}"
BUILD_DIR="${BUILD_DIR:-${PROJECT_ROOT}/build}"
SERVICE_BIN="${SERVICE_BIN:-${BUILD_DIR}/hello_task_worker}"

if [[ -f "${DEPLOY_ENV}" ]]; then
  # shellcheck disable=SC1090
  source "${DEPLOY_ENV}"
fi

export HELLO_SERVICE_STORAGE_MODE="${HELLO_SERVICE_STORAGE_MODE:-mysql_redis}"
export HELLO_SERVICE_MYSQL_HOST="${HELLO_SERVICE_MYSQL_HOST:-127.0.0.1}"
export HELLO_SERVICE_MYSQL_PORT="${HELLO_SERVICE_MYSQL_PORT:-3306}"
export HELLO_SERVICE_MYSQL_USER="${HELLO_SERVICE_MYSQL_USER:-game_backend}"
export HELLO_SERVICE_MYSQL_PASSWORD="${HELLO_SERVICE_MYSQL_PASSWORD:-change_me}"
export HELLO_SERVICE_MYSQL_DATABASE="${HELLO_SERVICE_MYSQL_DATABASE:-game_backend}"
export HELLO_SERVICE_MYSQL_AUTO_MIGRATE="${HELLO_SERVICE_MYSQL_AUTO_MIGRATE:-1}"
export HELLO_SERVICE_MYSQL_SCHEMA_FILE="${HELLO_SERVICE_MYSQL_SCHEMA_FILE:-db/mysql/001_game_backend.sql}"
export HELLO_SERVICE_REDIS_HOST="${HELLO_SERVICE_REDIS_HOST:-127.0.0.1}"
export HELLO_SERVICE_REDIS_PORT="${HELLO_SERVICE_REDIS_PORT:-6379}"
export HELLO_SERVICE_REDIS_PASSWORD="${HELLO_SERVICE_REDIS_PASSWORD:-}"
export HELLO_SERVICE_REDIS_DB="${HELLO_SERVICE_REDIS_DB:-0}"
export HELLO_SERVICE_REDIS_POOL_SIZE="${HELLO_SERVICE_REDIS_POOL_SIZE:-16}"
export OTEL_EXPORTER_OTLP_ENDPOINT="${OTEL_EXPORTER_OTLP_ENDPOINT:-http://127.0.0.1:4318}"
export OTEL_EXPORTER_OTLP_TRACES_ENDPOINT="${OTEL_EXPORTER_OTLP_TRACES_ENDPOINT:-http://127.0.0.1:4318/v1/traces}"
export OTEL_EXPORTER_OTLP_METRICS_ENDPOINT="${OTEL_EXPORTER_OTLP_METRICS_ENDPOINT:-http://127.0.0.1:4318/v1/metrics}"

exec "${SERVICE_BIN}"
